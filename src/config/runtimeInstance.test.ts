import { describe, expect, it } from "vitest";

import { runtimeInstanceProfileForIdentifier } from "./runtimeInstance";

describe("runtimeInstanceProfileForIdentifier", () => {
  it("isolates fork production ports and its registered auth scheme", () => {
    expect(
      runtimeInstanceProfileForIdentifier("com.theerasakping.tpagentstudio")
    ).toEqual({
      instanceId: 1,
      ideServerPort: 23_847,
      cliProxyPort: 27_888,
      authDeepLinkScheme: "tpagentstudio",
    });
  });

  it("keeps the fork dev identity separate from both production and upstream", () => {
    expect(
      runtimeInstanceProfileForIdentifier("com.theerasakping.tpagentstudio.dev")
    ).toEqual({
      instanceId: 100,
      ideServerPort: 23_946,
      cliProxyPort: 27_987,
      authDeepLinkScheme: "tpagentstudio-dev",
    });
  });

  it("matches the numbered and E2E fork profiles generated by the launcher", () => {
    for (const identifier of [
      "com.theerasakping.tpagentstudio.instance2",
      "com.theerasakping.tpagentstudio.e2e.instance2",
    ]) {
      expect(runtimeInstanceProfileForIdentifier(identifier)).toEqual({
        instanceId: 2,
        ideServerPort: 23_848,
        cliProxyPort: 27_889,
        authDeepLinkScheme: "tpagentstudio-instance2",
      });
    }
  });

  it("never routes unknown fork subidentifiers to upstream ports or orgii", () => {
    for (const identifier of [
      "com.theerasakping.tpagentstudio.instance1",
      "com.theerasakping.tpagentstudio.instance100",
      "com.theerasakping.tpagentstudio.instance2.invalid",
      "com.theerasakping.tpagentstudio.unknown",
    ]) {
      expect(runtimeInstanceProfileForIdentifier(identifier)).toEqual({
        instanceId: 1,
        ideServerPort: 23_847,
        cliProxyPort: 27_888,
        authDeepLinkScheme: "tpagentstudio",
      });
    }
  });

  it("routes dev HTTP, WebSocket and login away from the bundled app", () => {
    expect(runtimeInstanceProfileForIdentifier("org2ai.org2.dev")).toEqual({
      instanceId: 100,
      ideServerPort: 13_946,
      cliProxyPort: 17_987,
      authDeepLinkScheme: "orgii-dev",
    });
  });
  it("keeps the primary runtime coordinates together", () => {
    expect(runtimeInstanceProfileForIdentifier("org2ai.org2")).toEqual({
      instanceId: 1,
      ideServerPort: 13_847,
      cliProxyPort: 17_888,
      authDeepLinkScheme: "orgii",
    });
  });

  it("offsets every isolated runtime coordinate together", () => {
    expect(
      runtimeInstanceProfileForIdentifier("org2ai.org2.instance2")
    ).toEqual({
      instanceId: 2,
      ideServerPort: 13_848,
      cliProxyPort: 17_889,
      authDeepLinkScheme: "orgii-instance2",
    });
  });

  it("falls back for malformed and unbounded identifiers", () => {
    for (const identifier of [
      "org2ai.org2.instance1",
      "org2ai.org2.instance100",
      "org2ai.org2.instance2.extra",
      "other.orgii.instance2",
    ]) {
      expect(runtimeInstanceProfileForIdentifier(identifier).instanceId).toBe(
        1
      );
    }
  });
});
